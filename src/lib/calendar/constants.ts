/** Devanagari digits */
export const NP_DIGITS = ["०", "१", "२", "३", "४", "५", "६", "७", "८", "९"] as const;

export function toNepaliDigits(n: number | string): string {
  return String(n).replace(/\d/g, (d) => NP_DIGITS[Number(d)]);
}

